// Generate SQL to bulk-insert 40 pagination test products (idempotent).
// We build INSERT ... SELECT with a deterministic slug pattern that
// combines the row number with the brand so the cartesian product
// (40 nums × 10 brands) never collides on the unique slug index.
// Usage: node scripts/seed-pagination-gen.mjs && wrangler d1 execute ...
import fs from 'node:fs';

const BRANDS = ['TASANI', 'HITACHI', 'MITSUBISHI', 'SWAZER', 'NEWBEAT', 'GUPPO', 'MECO', 'MAKITA', 'BOSCH', 'STANLEY'];
const N = 40;
// Split into smaller batches so each statement stays under SQLite's
// 1MB statement limit (D1 in local mode is even stricter).
const BATCH = 5;

const header =
  '-- Auto-generated by scripts/seed-pagination-gen.mjs\n' +
  '-- Adds 40 demo products to exercise pagination. Idempotent.\n';

// Build all (slug, ...) rows once.
const allRows = [];
for (let n = 1; n <= N; n++) {
  for (const brand of BRANDS) {
    const safeBrand = brand.toLowerCase().replace(/[^a-z0-9]/g, '-');
    const slug = `pagetest-product-${String(n).padStart(3, '0')}-${safeBrand}`;
    const name = `อะไหล่ทดสอบเพจ #${n} (${brand})`.replace(/'/g, "''");
    const desc = `สินค้าทดสอบ pagination หมายเลข ${n} แบรนด์ ${brand}`.replace(/'/g, "''");
    const price = 290 + n * 35;
    const salePrice = n % 3 === 0 ? price - 50 : 'NULL';
    const stock = 10 + n;
    const isFeatured = n % 5 === 0 ? 1 : 0;
    const isNew = n % 4 === 0 ? 1 : 0;
    const catSubquery = `(SELECT id FROM Category WHERE parentId IS NULL AND isActive = 1 ORDER BY sortOrder ASC LIMIT 1 OFFSET ${n % 8})`;
    allRows.push(
      `SELECT lower(hex(randomblob(12))), '${name}', '${slug}', '${desc}', ${price}.0, ${salePrice === 'NULL' ? 'NULL' : salePrice + '.0'}, ${stock}, ${catSubquery}, 1, ${isFeatured}, ${isNew}, '${brand}', '["https://images.unsplash.com/photo-1581094271901-8022df4466f9?w=600"]', datetime('now'), datetime('now')`
    );
  }
}

const cols =
  'INSERT OR IGNORE INTO Product (id, name, slug, description, price, salePrice, stock, categoryId, isActive, isFeatured, isNew, brand, images, createdAt, updatedAt)';

const statements = [];
for (let i = 0; i < allRows.length; i += BATCH) {
  const chunk = allRows.slice(i, i + BATCH);
  // Each chunk: 5 rows -> "INSERT INTO Product (...) SELECT a UNION ALL SELECT b UNION ALL ..."  (5 terms)
  // SQLite caps compound SELECT at 8 terms, so 5 is safe.
  statements.push(cols + '\n' + chunk.join('\nUNION ALL\n') + ';');
}

fs.writeFileSync('/tmp/seed-pag.sql', header + statements.join('\n') + '\n');
console.log(`wrote /tmp/seed-pag.sql with ${statements.length} statement(s), ${allRows.length} rows`);